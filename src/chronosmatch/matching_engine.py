"""Simple price-time-priority limit order matching engine."""

from dataclasses import dataclass

from .order_format import BUY, SELL, Order, validate_order


@dataclass(frozen=True)
class Trade:
    buy_order_id: int
    sell_order_id: int
    price_ticks: int
    quantity: int
    timestamp_ns: int


@dataclass
class _RestingOrder:
    order: Order
    remaining_quantity: int
    sequence: int


class OrderBook:
    """Educational in-memory limit order book."""

    def __init__(self):
        self._bids: list[_RestingOrder] = []
        self._asks: list[_RestingOrder] = []
        self._sequence = 0
        self._seen_order_ids: set[int] = set()

    def submit_order(self, order: Order) -> list[Trade]:
        """Submit an order and return all trades generated by it."""
        validate_order(order)

        if order.order_id in self._seen_order_ids:
            raise ValueError(f"Duplicate order ID: {order.order_id}")

        self._seen_order_ids.add(order.order_id)
        incoming_quantity = order.quantity
        trades: list[Trade] = []

        opposite = self._asks if order.side == BUY else self._bids

        while incoming_quantity > 0 and opposite:
            # Best price first, then earliest timestamp, then arrival sequence.
            if order.side == BUY:
                opposite.sort(
                    key=lambda item: (
                        item.order.price_ticks,
                        item.order.timestamp_ns,
                        item.sequence,
                    )
                )
            else:
                opposite.sort(
                    key=lambda item: (
                        -item.order.price_ticks,
                        item.order.timestamp_ns,
                        item.sequence,
                    )
                )

            resting = opposite[0]

            crosses = (
                order.price_ticks >= resting.order.price_ticks
                if order.side == BUY
                else order.price_ticks <= resting.order.price_ticks
            )

            if not crosses:
                break

            quantity = min(incoming_quantity, resting.remaining_quantity)

            buy_id = order.order_id if order.side == BUY else resting.order.order_id
            sell_id = order.order_id if order.side == SELL else resting.order.order_id

            # Trades execute at the resting (maker) order's price.
            trades.append(
                Trade(
                    buy_order_id=buy_id,
                    sell_order_id=sell_id,
                    price_ticks=resting.order.price_ticks,
                    quantity=quantity,
                    timestamp_ns=max(
                        order.timestamp_ns, resting.order.timestamp_ns
                    ),
                )
            )

            incoming_quantity -= quantity
            resting.remaining_quantity -= quantity

            if resting.remaining_quantity == 0:
                opposite.remove(resting)

        # Any unfilled quantity rests on the book.
        if incoming_quantity > 0:
            self._sequence += 1
            resting_order = _RestingOrder(
                order=order,
                remaining_quantity=incoming_quantity,
                sequence=self._sequence,
            )
            own_side = self._bids if order.side == BUY else self._asks
            own_side.append(resting_order)

        return trades

    @property
    def best_bid(self) -> int | None:
        return max(
            (item.order.price_ticks for item in self._bids), default=None
        )

    @property
    def best_ask(self) -> int | None:
        return min(
            (item.order.price_ticks for item in self._asks), default=None
        )

    @property
    def resting_order_count(self) -> int:
        return len(self._bids) + len(self._asks)
    @property
    def resting_orders(self) -> list[dict]:
        orders = []
        for item in self._bids:
            orders.append({
                "side": "BUY",
                "order_id": item.order.order_id,
                "price_ticks": item.order.price_ticks,
                "remaining_quantity": item.remaining_quantity,
                "timestamp_ns": item.order.timestamp_ns,
            })
        for item in self._asks:
            orders.append({
                "side": "SELL",
                "order_id": item.order.order_id,
                "price_ticks": item.order.price_ticks,
                "remaining_quantity": item.remaining_quantity,
                "timestamp_ns": item.order.timestamp_ns,
            })
        return sorted(
            orders,
            key=lambda order: (
                0 if order["side"] == "BUY" else 1,
                -order["price_ticks"] if order["side"] == "BUY"
                else order["price_ticks"],
                order["timestamp_ns"],
            ),
        )